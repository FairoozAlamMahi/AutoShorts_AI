"""CookieManager: Converts JSON cookies (from Cookie-Editor) to Netscape format and extracts browser cookies."""
from __future__ import annotations

import json
import os
import re
import time
from datetime import datetime
from http.cookiejar import MozillaCookieJar
from pathlib import Path
from typing import Optional, Dict, Any, Tuple, List
import yt_dlp


class CookieManager:
    """Manages YouTube session cookies for age-restricted & login-gated videos."""

    DOWNLOADER_COOKIE_FILE = (Path(__file__).resolve().parent.parent.parent / "data" / "downloader_cookies.txt").resolve()
    LEGACY_COOKIE_FILE = (Path(__file__).resolve().parent.parent.parent / "data" / "cookies.txt").resolve()
    DEFAULT_COOKIE_FILE = DOWNLOADER_COOKIE_FILE

    @classmethod
    def resolve_cookie_file(cls, explicit_path: Optional[Path | str] = None) -> Path:
        """
        Resolves cookie path prioritizing isolated downloader_cookies.txt over legacy cookies.txt.
        Keeps downloading session credentials strictly isolated from brand publishing OAuth.
        """
        if explicit_path:
            return Path(explicit_path).resolve()
        if cls.DOWNLOADER_COOKIE_FILE.exists() and cls.DOWNLOADER_COOKIE_FILE.stat().st_size > 0:
            return cls.DOWNLOADER_COOKIE_FILE
        if cls.LEGACY_COOKIE_FILE.exists() and cls.LEGACY_COOKIE_FILE.stat().st_size > 0:
            return cls.LEGACY_COOKIE_FILE
        return cls.DOWNLOADER_COOKIE_FILE

    @classmethod
    def json_to_netscape(cls, json_str: str) -> str:
        """
        Converts a JSON cookie export (e.g. from 'Cookie-Editor' or 'EditThisCookie')
        into the standard Netscape HTTP Cookie File format accepted by yt-dlp, curl, etc.
        """
        raw_data = json.loads(json_str.strip())
        cookie_list: List[Dict[str, Any]] = []

        if isinstance(raw_data, list):
            cookie_list = raw_data
        elif isinstance(raw_data, dict):
            if "cookies" in raw_data and isinstance(raw_data["cookies"], list):
                cookie_list = raw_data["cookies"]
            else:
                # Dict of name: value
                for k, v in raw_data.items():
                    cookie_list.append({"name": k, "value": str(v), "domain": ".youtube.com", "path": "/"})
        else:
            raise ValueError("Expected a JSON array of cookie objects.")

        lines = [
            "# Netscape HTTP Cookie File",
            "# https://curl.se/docs/http-cookies.html",
            "# This file was generated by ShortsFactory Local",
            ""
        ]

        count = 0
        now_ts = int(time.time())
        one_year_ts = now_ts + 31536000

        for item in cookie_list:
            if not isinstance(item, dict):
                continue
            name = item.get("name")
            value = item.get("value")
            if not name or value is None:
                continue

            domain = item.get("domain", ".youtube.com")
            # Ensure domain starts with dot if it has subdomains
            flag = "TRUE" if domain.startswith(".") else "FALSE"
            path = item.get("path", "/")
            secure = "TRUE" if item.get("secure", False) else "FALSE"

            exp = item.get("expirationDate") or item.get("expires") or item.get("expiry")
            if exp is None or item.get("session", False):
                exp_ts = one_year_ts
            else:
                try:
                    exp_ts = int(float(exp))
                except (ValueError, TypeError):
                    exp_ts = one_year_ts

            lines.append(f"{domain}\t{flag}\t{path}\t{secure}\t{exp_ts}\t{name}\t{value}")
            count += 1

        if count == 0:
            raise ValueError("No valid cookies found in JSON input.")

        return "\n".join(lines) + "\n"

    @classmethod
    def save_cookie_content(
        cls,
        raw_content: str,
        output_path: Path | str = DEFAULT_COOKIE_FILE,
    ) -> Tuple[bool, str, int]:
        """
        Validates and saves pasted cookie text (either JSON or Netscape format).
        Returns: (success, message, count)
        """
        text = raw_content.strip()
        if not text:
            return False, "Error: Cookie input is empty.", 0

        target = Path(output_path).resolve()
        target.parent.mkdir(parents=True, exist_ok=True)

        netscape_text: str
        cookie_count = 0

        # Check if already Netscape format
        if text.startswith("# Netscape") or "\t" in text:
            netscape_text = text if text.startswith("# Netscape") else f"# Netscape HTTP Cookie File\n\n{text}\n"
            cookie_count = sum(1 for line in netscape_text.splitlines() if line and not line.startswith("#") and "\t" in line)
        else:
            # Attempt JSON conversion
            try:
                netscape_text = cls.json_to_netscape(text)
                cookie_count = sum(1 for line in netscape_text.splitlines() if line and not line.startswith("#") and "\t" in line)
            except Exception as e:
                return False, f"Failed to parse cookie input: {e}", 0

        # Validate with MozillaCookieJar
        temp_test = target.with_suffix(".tmp")
        temp_test.write_text(netscape_text, encoding="utf-8")
        try:
            jar = MozillaCookieJar(str(temp_test))
            jar.load(ignore_discard=True, ignore_expires=True)
            loaded_count = len(jar)
        except Exception as e:
            if temp_test.exists():
                temp_test.unlink()
            return False, f"[COOKIE_ERR_SYNTAX] Invalid cookie syntax: {e}", 0

        # Replace target file
        if temp_test.exists():
            if target.exists():
                target.unlink()
            temp_test.rename(target)

        # Check for key YouTube auth tokens
        auth_detected = any(c.name in ("LOGIN_INFO", "SID", "HSID", "SSID", "SAPISID") for c in jar)
        auth_note = " (Login credentials verified)" if auth_detected else " (Note: No LOGIN_INFO cookie detected)"

        return True, f"[COOKIE_OK] Successfully saved {loaded_count} cookies to {target.name}!{auth_note}", loaded_count

    @classmethod
    def extract_from_browser(
        cls,
        browser_name: str,
        output_path: Path | str = DEFAULT_COOKIE_FILE,
    ) -> Tuple[bool, str, int]:
        """
        Extracts YouTube cookies directly from an installed browser session.
        Returns: (success, message, count)
        """
        target = Path(output_path).resolve()
        target.parent.mkdir(parents=True, exist_ok=True)

        try:
            from yt_dlp.cookies import extract_cookies_from_browser

            jar = extract_cookies_from_browser(browser_name.lower())
            if not jar:
                return False, f"[BROWSER_ERR_EMPTY] No cookies found in {browser_name}.", 0

            # Filter for YouTube and Google domain cookies
            yt_jar = MozillaCookieJar(str(target))
            count = 0
            for cookie in jar:
                domain = cookie.domain or ""
                if "youtube" in domain or "google" in domain:
                    yt_jar.set_cookie(cookie)
                    count += 1

            if count == 0:
                # If domain filtering caught nothing, save the whole jar
                for cookie in jar:
                    yt_jar.set_cookie(cookie)
                    count += 1

            yt_jar.save(ignore_discard=True, ignore_expires=True)
            auth_detected = any(c.name in ("LOGIN_INFO", "SID", "HSID", "SSID") for c in yt_jar)
            auth_note = " (Login session active)" if auth_detected else ""
            return True, f"[BROWSER_OK] Extracted {count} cookies from {browser_name.title()}!{auth_note}", count

        except Exception as e:
            err_msg = re.sub(r"\x1b\[[0-9;]*m", "", str(e)).strip()
            if any(k in err_msg.lower() for k in ("could not copy", "locked", "7271", "permission denied")):
                return False, (
                    f"[BROWSER_ERR_LOCKED] Browser locked: {browser_name.title()} is currently open on Windows and locking its cookie database. "
                    f"Fix: Close {browser_name.title()} completely, or paste your cookies JSON below (recommended — works while browser is open!)."
                ), 0
            return False, f"[BROWSER_ERR_FAILED] Failed to extract cookies from {browser_name}: {err_msg}", 0

    @classmethod
    def get_cookie_status(cls, cookies_path: Optional[Path | str] = None) -> Dict[str, Any]:
        """Inspects status of the saved cookies file."""
        target = cls.resolve_cookie_file(cookies_path)
        if not target.exists() or target.stat().st_size == 0:
            return {
                "exists": False,
                "count": 0,
                "has_login_info": False,
                "display": "No saved cookies (Age-restricted videos will prompt for login)",
            }

        try:
            jar = MozillaCookieJar(str(target))
            jar.load(ignore_discard=True, ignore_expires=True)
            count = len(jar)
            has_login = any(c.name == "LOGIN_INFO" for c in jar)
            has_sid = any(c.name in ("SID", "HSID") for c in jar)
            mod_time = datetime.fromtimestamp(target.stat().st_mtime).strftime("%Y-%m-%d %H:%M")

            status_str = f"Active ({count} cookies, modified {mod_time})"
            if has_login or has_sid:
                status_str += " — Authenticated YouTube Session Active ✅"
            else:
                status_str += " — Guest Session (Missing LOGIN_INFO) ⚠️"

            return {
                "exists": True,
                "count": count,
                "has_login_info": has_login or has_sid,
                "display": status_str,
            }
        except Exception as e:
            return {
                "exists": True,
                "count": 0,
                "has_login_info": False,
                "display": f"Saved file present but invalid: {e}",
            }

    @classmethod
    def remove_saved_cookies(cls, cookies_path: Optional[Path | str] = None) -> bool:
        """Deletes the saved cookies file."""
        target = cls.resolve_cookie_file(cookies_path)
        if target.exists():
            target.unlink()
            return True
        return False

    @classmethod
    def test_cookie_authentication(cls, cookies_path: Optional[Path | str] = None) -> Tuple[bool, str]:
        """
        Tests whether the cookies successfully authenticate with YouTube.
        Uses local JS runtimes (Node.js) to solve YouTube signature challenges cleanly.
        """
        import shutil
        target = cls.resolve_cookie_file(cookies_path)
        if not target.exists() or target.stat().st_size == 0:
            return False, "[AUTH_ERR_NO_COOKIES] No cookies.txt file found. Please paste cookies or link a browser first."

        js_rts = {}
        for rt in ("node", "deno", "bun"):
            if shutil.which(rt):
                js_rts[rt] = {}

        ydl_opts = {
            "skip_download": True,
            "quiet": True,
            "no_warnings": True,
            "cookiefile": str(target),
            "extract_flat": True,
            "no_color": True,
        }
        if js_rts:
            ydl_opts["js_runtimes"] = js_rts

        # Test video: Rick Astley (standard public check)
        test_url = "https://www.youtube.com/watch?v=dQw4w9WgXcQ"
        try:
            with yt_dlp.YoutubeDL(ydl_opts) as ydl:
                info = ydl.extract_info(test_url, download=False)
                title = info.get("title", "Unknown")
                return True, f"[AUTH_OK] Cookies verified! Connected to YouTube as authenticated session (Fetched '{title[:30]}...')."
        except Exception as e:
            err_str = re.sub(r"\x1b\[[0-9;]*m", "", str(e)).strip()
            if "The page needs to be reloaded" in err_str or "rotated" in err_str.lower():
                return False, (
                    "[AUTH_ERR_SESSION_ROTATED] YouTube reported 'The page needs to be reloaded'. "
                    "This happens when active YouTube tabs in your browser rotate session tokens after export. "
                    "Fix: Open an Incognito/Private window, visit https://www.youtube.com/robots.txt, "
                    "copy cookies with Cookie-Editor, close that Incognito window, and paste."
                )
            return False, f"[AUTH_ERR_FAILED] YouTube verification failed: {err_str}"
