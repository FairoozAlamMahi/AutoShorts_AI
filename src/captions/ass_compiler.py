"""ASS (Advanced SubStation Alpha) subtitle compiler supporting Creator Pop and Classic styles."""
from __future__ import annotations

import re
from pathlib import Path
from typing import List, Optional
from .phrase_chunker import CaptionChunkDTO
from ..config.schema import CaptionMode, CaptionTheme, LayoutMode


class ASSCompiler:
    """Compiles styled .ass subtitle files for libass burning."""

    # Colors in ASS &HAABBGGRR& format
    CYBER_YELLOW = "&H0000E6FF&"   # #FFE600 (MrBeast style)
    NEON_GREEN = "&H0066FF00&"     # #00FF66 (Cyber green)
    TIKTOK_RED = "&H005500FF&"     # #FF0055 (TikTok pop)
    ELECTRIC_BLUE = "&H00FFE500&"  # #00E5FF (Electric cyan)
    CLEAN_WHITE = "&H00FFFFFF&"    # #FFFFFF
    INACTIVE_WHITE = "&H00FFFFFF&"

    THEME_MAP = {
        CaptionTheme.MRBEAST_YELLOW: CYBER_YELLOW,
        CaptionTheme.NEON_CYBER_GREEN: NEON_GREEN,
        CaptionTheme.TIKTOK_RED_BOX: TIKTOK_RED,
        CaptionTheme.ELECTRIC_BLUE: ELECTRIC_BLUE,
        CaptionTheme.CLEAN_WHITE: CLEAN_WHITE,
    }

    @classmethod
    def build_header(
        cls,
        font_size: int = 68,
        play_res_x: int = 1080,
        play_res_y: int = 1920,
        margin_v_anim: int = 380,
        margin_v_classic: int = 180,
    ) -> str:
        classic_size = max(24, int(font_size * 0.76))
        return f"""[Script Info]
; Script generated by ShortsFactory Local
Title: ShortsFactory Captions
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: {play_res_x}
PlayResY: {play_res_y}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: AnimatedPop,Montserrat ExtraBold,{font_size},&H00FFFFFF,&H000000FF,&H00000000,&H80000000,1,0,0,0,100,100,0,0,1,4.5,2,2,40,40,{margin_v_anim},1
Style: Classic,Montserrat ExtraBold,{classic_size},&H00FFFFFF,&H000000FF,&H00000000,&H80000000,1,0,0,0,100,100,0,0,1,3.5,1,2,60,60,{margin_v_classic},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

    @classmethod
    def format_ass_timestamp(cls, seconds: float) -> str:
        """Converts seconds into ASS timestamp format: H:MM:SS.cc"""
        total_cs = int(round(seconds * 100))
        cs = total_cs % 100
        total_s = total_cs // 100
        s = total_s % 60
        total_m = total_s // 60
        m = total_m % 60
        h = total_m // 60
        return f"{h}:{m:02d}:{s:02d}.{cs:02d}"

    @classmethod
    def sanitize_text(cls, text: str) -> str:
        """
        Escapes characters that could break ASS syntax:
        - Curly braces {} are stripped or escaped
        - Backslashes are replaced
        - Whitespace normalized
        """
        if not text:
            return ""
        # Strip or replace braces that libass interprets as override tags
        clean = text.replace("{", "(").replace("}", ")")
        clean = clean.replace("\\", "/")
        clean = re.sub(r"[\r\n]+", " ", clean)
        return clean.strip()

    @classmethod
    def compile_ass(
        cls,
        chunks: List[CaptionChunkDTO],
        mode: CaptionMode,
        output_path: Path | str,
        theme: CaptionTheme = CaptionTheme.MRBEAST_YELLOW,
        font_size: int = 68,
        highlight_color: Optional[str] = None,
        layout_mode: Optional[LayoutMode] = None,
    ) -> Path:
        """
        Compiles .ass file from timed caption chunks with custom themes and font sizes.
        Supports BURNED_IN_ANIMATED and BURNED_IN_CLASSIC styles.
        Adapts subtitle margins and PlayRes canvas coordinates to match layout aspect ratio.
        """
        out = Path(output_path).resolve()
        out.parent.mkdir(parents=True, exist_ok=True)

        # Coordinate resolution and margins adapted to layout aspect ratio
        if layout_mode in (LayoutMode.LAYOUT_4_3_BLUR_FIT, LayoutMode.LAYOUT_4_3_HORIZONTAL):
            play_res_x = 1440
            play_res_y = 1080
            margin_v_anim = 160
            margin_v_classic = 90
        elif layout_mode == LayoutMode.LAYOUT_RAW_16_9:
            play_res_x = 1920
            play_res_y = 1080
            margin_v_anim = 160
            margin_v_classic = 90
        else:
            play_res_x = 1080
            play_res_y = 1920
            margin_v_anim = 380
            margin_v_classic = 180

        active_hl = highlight_color or cls.THEME_MAP.get(theme, cls.CYBER_YELLOW)
        lines: List[str] = [
            cls.build_header(
                font_size=font_size,
                play_res_x=play_res_x,
                play_res_y=play_res_y,
                margin_v_anim=margin_v_anim,
                margin_v_classic=margin_v_classic,
            )
        ]

        if mode == CaptionMode.BURNED_IN_CLASSIC:
            # Classic style: single subtitle event per chunk
            for chunk in chunks:
                if not chunk.text.strip():
                    continue
                start_str = cls.format_ass_timestamp(chunk.start_sec)
                end_str = cls.format_ass_timestamp(chunk.end_sec)
                clean_text = cls.sanitize_text(chunk.text)
                lines.append(f"Dialogue: 0,{start_str},{end_str},Classic,,0,0,0,,{clean_text}\n")

        elif mode in (CaptionMode.BURNED_IN_ANIMATED, CaptionMode.BURNED_IN_PLUS_SIDECAR):
            # Animated Pop style: word-by-word active highlight & scale pop
            for chunk in chunks:
                words = chunk.words
                if not words:
                    continue

                for i, active_w in enumerate(words):
                    w_start = cls.format_ass_timestamp(active_w.start_sec)
                    w_end = cls.format_ass_timestamp(active_w.end_sec)
                    if active_w.end_sec <= active_w.start_sec:
                        continue

                    # Construct text with active word highlighted and scaled
                    parts: List[str] = []
                    for j, w in enumerate(words):
                        clean_w = cls.sanitize_text(w.word)
                        if j == i:
                            # Active word: Theme highlight + 115% scale pop
                            parts.append(f"{{\\c{active_hl}\\fscx115\\fscy115}}{clean_w}{{\\rAnimatedPop}}")
                        else:
                            # Inactive word: Plain white + 100% scale
                            parts.append(f"{{\\c{cls.INACTIVE_WHITE}\\fscx100\\fscy100}}{clean_w}")

                    event_text = " ".join(parts)
                    lines.append(f"Dialogue: 0,{w_start},{w_end},AnimatedPop,,0,0,0,,{event_text}\n")

        out.write_text("".join(lines), encoding="utf-8")
        return out
